import {readFileSync, writeFileSync} from 'node:fs';

const tokens = JSON.parse(readFileSync(new URL('../src/design-tokens.tokens.json', import.meta.url), 'utf8'));

// Resolve Figma aliases rather than copying their current colour values.
function resolve(path, seen = new Set()) {
  if (seen.has(path)) throw new Error(`Circular token reference: ${path}`);
  seen.add(path);
  const token = path.split('.').reduce((value, key) => value?.[key], tokens);
  if (!token || !('value' in token)) throw new Error(`Missing token: ${path}`);
  const value = token.value;
  return typeof value === 'string' && value.startsWith('{')
    ? resolve(value.slice(1, -1), seen)
    : value;
}

const variables = {
  background: resolve('color.brand.client.color.1'),
  accent: resolve('color.brand.client.color.2'),
  text: resolve('[themes].components.navitem.label'),
  muted: resolve('[themes].text.secondary'),
  icon: resolve('[core] colors.grey.400'),
  'font-family': `"${resolve('typography.components.nav-item-default.fontFamily')}", system-ui, sans-serif`,
  'font-size': `${resolve('typography.components.nav-item-default.fontSize')}px`,
  'line-height': `${resolve('typography.components.nav-item-default.lineHeight')}px`,
  'font-weight': resolve('typography.components.nav-item-default.fontWeight'),
  'active-weight': resolve('typography.components.nav-item-active.fontWeight'),
  'heading-size': `${resolve('typography.components.nav-subheader.fontSize')}px`,
  'heading-weight': resolve('typography.components.nav-subheader.fontWeight'),
  radius: `${resolve('[core] radius.radius-1')}px`,
};
for (const [name, key] of Object.entries({xs: '0,5', sm: '1', md: '1,5', lg: '2', xl: '3', xxl: '4', row: '5'})) {
  variables[`space-${name}`] = `${resolve(`[core] spacing.spacing-${key}`)}px`;
}

writeFileSync(new URL('../src/css/sidebar-tokens.css', import.meta.url),
  `/* Generated by scripts/sidebar-tokens.mjs from design-tokens.tokens.json. */\n:root {\n${Object.entries(variables).map(([key, value]) => `  --n1-sidebar-${key}: ${value};`).join('\n')}\n}\n`);
