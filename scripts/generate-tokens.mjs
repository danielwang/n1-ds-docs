import {readFileSync, writeFileSync} from 'node:fs';

// Generates the site-wide design-token CSS custom properties consumed by
// src/css/custom.css from the Figma token export. Keeping this separate from
// scripts/sidebar-tokens.mjs mirrors that script's "resolve, don't hardcode"
// approach for the rest of the site (navbar, footer, buttons, typography,
// admonitions, etc.), so brand colours/spacing/radius/shadows/type all trace
// back to src/design-tokens.tokens.json instead of hand-picked hex values.

const tokens = JSON.parse(readFileSync(new URL('../src/design-tokens.tokens.json', import.meta.url), 'utf8'));

function resolve(path, seen = new Set()) {
  if (seen.has(path)) throw new Error(`Circular token reference: ${path}`);
  seen.add(path);
  const token = path.split('.').reduce((value, key) => value?.[key], tokens);
  if (!token || !('value' in token)) throw new Error(`Missing token: ${path}`);
  const value = token.value;
  return typeof value === 'string' && value.startsWith('{')
    ? resolve(value.slice(1, -1), seen)
    : value;
}

// Figma exports 8-digit hex (RRGGBBAA); drop a trailing opaque alpha so plain
// 6-digit hex reaches the browser, while keeping real alpha when present.
function hex(path) {
  const value = String(resolve(path));
  return value.length === 9 && value.toLowerCase().endsWith('ff') ? value.slice(0, 7) : value;
}

function px(path) {
  return `${resolve(path)}px`;
}

function rem(path) {
  return `${resolve(path) / 16}rem`;
}

function shadow(path) {
  const {offsetX, offsetY, radius, spread, color} = resolve(path);
  return `${offsetX}px ${offsetY}px ${radius}px ${spread}px ${color}`;
}

const vars = {};

// Neutral scale (used for text, surfaces, borders in both colour modes).
for (const step of ['100', '200', '300', '400', '500', '600', '700', '800', '900']) {
  vars[`grey-${step}`] = hex(`[core] colors.grey.${step}`);
}
vars['white'] = hex('[core] colors.white.main');

// Brand accents, kept distinct from the generic/neutral "primary" core colour.
vars['primary'] = hex('color.brand.blue');
vars['accent'] = hex('color.brand.blue light');
vars['accent-purple'] = hex('color.brand.purple');

// Semantic status colours, shared by admonitions, tags and form feedback.
for (const status of ['success', 'warning', 'error', 'info']) {
  for (const shade of ['light', 'main', 'dark']) {
    vars[`${status}-${shade}`] = hex(`[core] colors.${status}.${shade}`);
  }
}

// Spacing scale (4px baseline grid), named like the sidebar token set.
const spacingSteps = {
  '3xs': '0,5', '2xs': '0,75', xs: '1', sm: '1,5', md: '2',
  lg: '3', xl: '4', '2xl': '5', '3xl': '6', '4xl': '7',
};
for (const [name, key] of Object.entries(spacingSteps)) {
  vars[`space-${name}`] = px(`[core] spacing.spacing-${key}`);
}

// Corner radius scale. Only the sizes actually used across the site are
// generated, matching the "avoid oversized decorative elements" guidance for
// a content-focused documentation site.
const radiusSteps = {xs: '0,5', sm: '0,75', md: '1', lg: '1,5'};
for (const [name, key] of Object.entries(radiusSteps)) {
  vars[`radius-${name}`] = px(`[core] radius.radius-${key}`);
}
vars['radius-pill'] = '9999px';

// Elevation, expressed as ready-to-use box-shadow values (low -> high).
for (const level of ['z4', 'z8']) {
  vars[`shadow-${level.slice(1)}`] = shadow(`effect.shadow.${level}`);
}
vars['shadow-card'] = shadow('effect.shadow.card');

// Typography scale (desktop). Font sizes/line-heights convert px -> rem so
// the scale still respects a visitor's browser font-size preference.
vars['font-family'] = `"${resolve('typography.desktop.h1.fontFamily')}", system-ui, -apple-system, sans-serif`;
vars['font-family-mono'] = '"SFMono-Regular", ui-monospace, Consolas, Menlo, monospace';
vars['font-weight-regular'] = String(resolve('typography.desktop.body1.fontWeight'));
vars['font-weight-medium'] = String(resolve('typography.desktop.subtitle2.fontWeight'));
vars['font-weight-bold'] = String(resolve('font weight.bold'));

for (const scale of ['h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'subtitle1', 'subtitle2', 'body1', 'body2', 'caption', 'overline']) {
  vars[`type-${scale}-size`] = rem(`typography.desktop.${scale}.fontSize`);
  vars[`type-${scale}-line`] = rem(`typography.desktop.${scale}.lineHeight`);
  vars[`type-${scale}-weight`] = String(resolve(`typography.desktop.${scale}.fontWeight`));
}

const css = `/* Generated by scripts/generate-tokens.mjs from design-tokens.tokens.json. */
:root {
${Object.entries(vars).map(([key, value]) => `  --ds-${key}: ${value};`).join('\n')}
}
`;

writeFileSync(new URL('../src/css/tokens.css', import.meta.url), css);
